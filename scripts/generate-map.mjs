// Generates src/content/worldDots.ts: a dot-matrix land map (equirectangular), built from Natural Earth via world-atlas.
import { readFileSync, writeFileSync } from "node:fs";
import { feature } from "topojson-client";
import { geoContains } from "d3-geo";
const topo = JSON.parse(readFileSync("node_modules/world-atlas/land-110m.json", "utf8"));
const land = feature(topo, topo.objects.land);
const W = 200, H = 100; // grid columns/rows
const dots = [];
for (let r = 0; r < H; r++) {
  const lat = 83 - (r / (H - 1)) * (83 + 57); // 83N .. -57S
  for (let c = 0; c < W; c++) {
    const lon = -180 + (c / (W - 1)) * 360;
    if (geoContains(land, [lon, lat])) dots.push([c, r]);
  }
}
const out = `// AUTO-GENERATED by scripts/generate-map.mjs. Do not edit.\nexport const MAP_COLS = ${W};\nexport const MAP_ROWS = ${H};\nexport const MAP_LAT_TOP = 83;\nexport const MAP_LAT_BOTTOM = -57;\nexport const worldDots: [number, number][] = ${JSON.stringify(dots)};\n`;
writeFileSync("src/content/worldDots.ts", out);
console.log("dots", dots.length);
